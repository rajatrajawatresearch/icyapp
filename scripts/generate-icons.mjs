// Renders the app icons from public/brand/icon.svg (the single source for the
// logo). Run after changing the logo:  node scripts/generate-icons.mjs
import { readFile, writeFile } from "node:fs/promises";
import sharp from "sharp";

const svg = await readFile("public/brand/icon.svg", "utf8");

// Full-bleed variant for platforms that apply their own mask (Android
// adaptive icons, iOS home screen): square background, artwork kept inside
// the central safe zone.
const fullBleed = (scale) =>
  svg
    .replaceAll('rx="116"', 'rx="0"')
    .replace(
      /(<ellipse[\s\S]*)(<\/svg>)/,
      (_, art, close) =>
        `<g transform="translate(256 256) scale(${scale}) translate(-256 -256)">${art}</g>${close}`,
    );

const png = (source, size) =>
  sharp(Buffer.from(source), { density: 300 }).resize(size, size).png({ compressionLevel: 9 });

await png(svg, 192).toFile("public/icons/icon-192.png");
await png(svg, 512).toFile("public/icons/icon-512.png");
await png(fullBleed(0.78), 512).toFile("public/icons/maskable-512.png");
await png(fullBleed(0.9), 180).toFile("public/icons/apple-touch-icon.png");
await png(svg, 48).toFile("public/icons/favicon-48.png");

// Monochrome badge for Android's notification tray: white diamond on transparent.
const badge = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 96 96">
  <g fill="none" stroke="#fff" stroke-width="6" stroke-linejoin="round" stroke-linecap="round">
    <path d="M30 18H66L86 40 48 82 10 40Z"/><path d="M10 40H86M30 18 38 40 48 18 58 40 66 18M38 40 48 82 58 40"/>
  </g></svg>`;
await png(badge, 96).toFile("public/icons/badge-96.png");
// The diamond without its tile, for the panel on the login screen.
const cube = svg.replace(/\s*<rect[^>]*\/>/g, "");
await writeFile("public/brand/cube.svg", cube);

await writeFile("public/icons/.generated", "Generated by scripts/generate-icons.mjs from public/brand/icon.svg\n");
console.log("icons written to public/icons");
